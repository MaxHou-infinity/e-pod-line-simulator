"""
供应链关键术语库 - 术语与意义梗概

用于在输入/展示界面提供术语速查，降低新手理解成本。
"""

GLOSSARY = [
    ("工序", "产线上的一个加工环节，如注油、焊接、包装。"),
    ("并联", "多人同时加工不同物料，产能 = 人数 × 单人产能。"),
    ("协同", "多人共同完成同一物料，产能不随人数叠加。"),
    ("单颗耗时", "加工 1 颗物料所需的理论时间（秒）。"),
    ("产能", "单位小时可产出的物料数（颗/h）。"),
    ("OEE", "设备综合效率：实际产出 ÷ 理论产出（0-1）。"),
    ("人员效率", "技能/疲劳等因素对理论效率的折减（0-1）。"),
    ("切换时间", "更换口味/型号时的停机时间（分钟）。"),
    ("WIP", "在制品：工序缓冲区内等待加工的物料数量（颗）。"),
    ("瓶颈", "产能最低的工序，决定整线产出上限。"),
    ("缓冲区容量", "工序前可暂存的最大物料数，满则上游堵塞。"),
    ("产线平衡率", "瓶颈产能 ÷ 平均产能，越接近 1 越平衡。"),
    ("UPPH", "每人每小时产出 = 瓶颈产能 ÷ 总人数（颗/人·h）。"),
    ("班次时长", "单班工作时间（小时）。"),
    ("休息时间", "班次内休息时长（分钟），影响有效工时。"),
    ("时薪", "每名工人每小时工资（元/小时）。"),
    ("日成本", "总人数 × 时薪 × 班次时长（元/天）。"),
    ("日产量", "瓶颈产能 × 有效工时（班次时长 - 休息时间）。"),
    ("单颗成本", "日成本 ÷ 日产量（元/颗）。"),
]


def glossary_text() -> str:
    """返回全部术语的纯文本（用于复制/导出）"""
    return "\n".join(f"{term}：{desc}" for term, desc in GLOSSARY)
